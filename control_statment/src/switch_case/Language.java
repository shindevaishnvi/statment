package switch_case;

public class Language {
	public static void main(String[] args) {
		int lang=4;
		switch(lang) {
		case 1:
			System.out.println("java");
			break;
		case 2:
			System.out.println("python");
			break;
		case 3:
			System.out.println("c++");
			break;
		case 4:
			System.out.println("javascript");
			break;
		
		default:
			System.out.println("error");
		}
			
		}
}
